/* --------------------------------------------------
   Translate a single text value
-------------------------------------------------- */

function translateText(text) {
    const clean = text.trim();

    if (T[clean]) {
        return text.replace(clean, T[clean]);
    }

    /* Dynamic dashboard text */
    if (clean.startsWith("Welcome, ")) {
        const name = clean.substring(9);
        return text.replace(clean, "ಸ್ವಾಗತ, " + name);
    }

    if (clean.startsWith("Profile location:")) {
        return text.replace(
            clean,
            clean.replace("Profile location:", "ಪ್ರೊಫೈಲ್ ಸ್ಥಳ:")
        );
    }

    return text;
}


/* --------------------------------------------------
   Translate page
-------------------------------------------------- */

function translatePage() {

    const language = localStorage.getItem("language") || "en";

    const selector = document.getElementById("language");

    if (selector) {
        selector.value = language;
    }

    if (language !== "kn") {
        document.documentElement.lang = "en";
        return;
    }

    document.documentElement.lang = "kn";
    /* Translate elements with data-translate */
    document.querySelectorAll("[data-translate]").forEach(element => {
       const key = element.getAttribute("data-translate");

    if (T[key]) {
        element.textContent = T[key];
    }
    });
    /* Translate normal text */
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );

    const nodes = [];
    let node;

    while (node = walker.nextNode()) {
        nodes.push(node);
    }

    nodes.forEach(node => {

        /* Don't modify script/style content */
        if (
            node.parentElement &&
            (
                node.parentElement.tagName === "SCRIPT" ||
                node.parentElement.tagName === "STYLE"
            )
        ) {
            return;
        }

        const translated = translateText(node.nodeValue);

        if (translated !== node.nodeValue) {
            node.nodeValue = translated;
        }
    });


    /* Translate input placeholders */
    document.querySelectorAll(
        "input[placeholder], textarea[placeholder]"
    ).forEach(element => {

        const placeholder = element.placeholder;

        if (T[placeholder]) {
            element.placeholder = T[placeholder];
        }
    });
}


/* --------------------------------------------------
   Language selector
-------------------------------------------------- */

function setLanguage(language) {

    localStorage.setItem("language", language);

    document.cookie =
        "language=" +
        language +
        ";path=/;max-age=31536000";

    location.reload();
}


/* --------------------------------------------------
   Speech recognition
-------------------------------------------------- */

function startSpeech() {

    const Recognition =
        window.SpeechRecognition ||
        window.webkitSpeechRecognition;

    if (!Recognition) {

        alert(
            "Speech recognition is not supported in this browser."
        );

        return;
    }

    const recognition = new Recognition();

    const language =
        localStorage.getItem("language") === "kn"
            ? "kn-IN"
            : "en-IN";

    recognition.lang = language;

    recognition.onresult = function(event) {

        const voiceBox =
            document.getElementById("voiceText");

        if (voiceBox) {
            voiceBox.value =
                event.results[0][0].transcript;
        }
    };

    recognition.start();
}


/* --------------------------------------------------
   Run after page loads
-------------------------------------------------- */

document.addEventListener(
    "DOMContentLoaded",
    translatePage
);
